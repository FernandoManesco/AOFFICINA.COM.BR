-- v004 — Pagamentos do pedido (fechamento). Base para o WebFinanceiro.
CREATE TABLE IF NOT EXISTS PAGAMENTO (
  ID            INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  PEDIDO_ID     INT UNSIGNED NOT NULL,
  FORMA         ENUM('DINHEIRO','PIX','DEBITO','CREDITO','BOLETO') NOT NULL,
  VALOR_CENT    BIGINT NOT NULL,
  PARCELAS      TINYINT UNSIGNED NOT NULL DEFAULT 1,
  PAGO          TINYINT(1) NOT NULL DEFAULT 0,
  PAGO_EM       DATETIME NULL,
  VENCIMENTO    DATE NULL,                      -- boleto
  NOSSO_NUMERO  VARCHAR(30) NULL,               -- boleto (fictício até integrar o banco)
  TXID          VARCHAR(40) NULL,               -- pix
  RECEBIDO_POR  INT UNSIGNED NULL,
  OBS           VARCHAR(200) NULL,
  CRIADO_EM     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_PAG_PEDIDO FOREIGN KEY (PEDIDO_ID) REFERENCES PEDIDO(ID),
  CONSTRAINT FK_PAG_USUARIO FOREIGN KEY (RECEBIDO_POR) REFERENCES USUARIO(ID),
  KEY IX_PAG_PEDIDO (PEDIDO_ID),
  KEY IX_PAG_ABERTO (PAGO, VENCIMENTO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
