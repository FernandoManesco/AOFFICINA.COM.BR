-- v002 — Peças, mão de obra (serviços) e Pedido (orçamento -> pedido/OS).
-- Dinheiro em centavos (BIGINT). Quantidades DECIMAL. Estoque por lote vem na v003.

CREATE TABLE IF NOT EXISTS PECA (
  ID                INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  EMPRESA_ID        INT UNSIGNED NOT NULL,
  CODIGO            VARCHAR(30)  NOT NULL,          -- código interno / SKU
  CODIGO_FABRICANTE VARCHAR(40)  NULL,              -- part number
  CODIGO_BARRAS     VARCHAR(20)  NULL,
  NOME              VARCHAR(120) NOT NULL,
  DESCRICAO         TEXT         NULL,
  FABRICANTE        VARCHAR(60)  NULL,              -- marca da peça (Bosch, Cofap...)
  APLICACAO         VARCHAR(255) NULL,              -- texto livre: "Gol G5 1.0 2009-2013"
  UNIDADE           VARCHAR(6)   NOT NULL DEFAULT 'UN',
  NCM               VARCHAR(8)   NULL,
  PRECO_CUSTO_CENT  BIGINT       NOT NULL DEFAULT 0,
  PRECO_VENDA_CENT  BIGINT       NOT NULL DEFAULT 0,
  ESTOQUE_MIN       DECIMAL(10,3) NOT NULL DEFAULT 0,
  TEM_VALIDADE      TINYINT(1)   NOT NULL DEFAULT 0, -- fluidos/borrachas
  ATIVO             TINYINT(1)   NOT NULL DEFAULT 1,
  CRIADO_EM         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_PECA_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID),
  UNIQUE KEY UK_PECA_CODIGO (EMPRESA_ID, CODIGO),
  KEY IX_PECA_NOME (EMPRESA_ID, NOME),
  KEY IX_PECA_FABR (CODIGO_FABRICANTE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Mão de obra: valor por hora + tempo previsto; opcionalmente valor fixo.
CREATE TABLE IF NOT EXISTS SERVICO (
  ID                 INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  EMPRESA_ID         INT UNSIGNED NOT NULL,
  CODIGO             VARCHAR(20)  NOT NULL,
  NOME               VARCHAR(120) NOT NULL,
  DESCRICAO          TEXT         NULL,
  CATEGORIA          VARCHAR(40)  NULL,             -- Motor, Freios, Suspensão, Elétrica...
  VALOR_HORA_CENT    BIGINT       NOT NULL DEFAULT 0,
  TEMPO_PREVISTO_MIN INT UNSIGNED NOT NULL DEFAULT 60,
  VALOR_FIXO_CENT    BIGINT       NULL,             -- se preenchido, ignora hora x tempo
  ATIVO              TINYINT(1)   NOT NULL DEFAULT 1,
  CRIADO_EM          DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_SERV_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID),
  UNIQUE KEY UK_SERV_CODIGO (EMPRESA_ID, CODIGO),
  KEY IX_SERV_NOME (EMPRESA_ID, NOME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Pedido: nasce como ORCAMENTO; aprovado vira PEDIDO (mesmo registro, ganha NUMERO_PEDIDO).
CREATE TABLE IF NOT EXISTS PEDIDO (
  ID                  INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  EMPRESA_ID          INT UNSIGNED NOT NULL,
  OFICINA_ID          INT UNSIGNED NOT NULL,
  NUMERO_ORCAMENTO    INT UNSIGNED NULL,
  NUMERO_PEDIDO       INT UNSIGNED NULL,
  TIPO                ENUM('ORCAMENTO','PEDIDO') NOT NULL DEFAULT 'ORCAMENTO',
  STATUS              ENUM('ABERTO','ENVIADO','APROVADO','RECUSADO','EM_EXECUCAO','AGUARDANDO_PECA',
                           'CONCLUIDO','ENTREGUE','FATURADO','CANCELADO') NOT NULL DEFAULT 'ABERTO',
  CLIENTE_ID          INT UNSIGNED NOT NULL,
  VEICULO_ID          INT UNSIGNED NOT NULL,
  AGENDA_ID           INT UNSIGNED NULL,
  FUNCIONARIO_ID      INT UNSIGNED NULL,            -- mecânico responsável
  KM_ENTRADA          INT UNSIGNED NULL,
  GUINCHO             TINYINT(1)   NOT NULL DEFAULT 0,
  QUEIXA              TEXT         NULL,            -- relato do cliente
  DIAGNOSTICO         TEXT         NULL,
  OBSERVACAO          TEXT         NULL,
  PREVISAO_ENTREGA    DATETIME     NULL,
  VALIDADE_ORCAMENTO  DATE         NULL,
  TOTAL_SERVICOS_CENT BIGINT NOT NULL DEFAULT 0,
  TOTAL_PECAS_CENT    BIGINT NOT NULL DEFAULT 0,
  DESCONTO_CENT       BIGINT NOT NULL DEFAULT 0,
  TOTAL_CENT          BIGINT NOT NULL DEFAULT 0,
  ABERTO_EM           DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  APROVADO_EM         DATETIME NULL,
  APROVADO_POR_NOME   VARCHAR(100) NULL,            -- quem autorizou (cliente)
  CONCLUIDO_EM        DATETIME NULL,
  ENTREGUE_EM         DATETIME NULL,
  CRIADO_POR          INT UNSIGNED NULL,
  ATUALIZADO_EM       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_PED_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID),
  CONSTRAINT FK_PED_OFICINA FOREIGN KEY (OFICINA_ID) REFERENCES OFICINA(ID),
  CONSTRAINT FK_PED_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE(ID),
  CONSTRAINT FK_PED_VEICULO FOREIGN KEY (VEICULO_ID) REFERENCES VEICULO(ID),
  CONSTRAINT FK_PED_AGENDA  FOREIGN KEY (AGENDA_ID) REFERENCES AGENDA(ID),
  CONSTRAINT FK_PED_FUNC    FOREIGN KEY (FUNCIONARIO_ID) REFERENCES FUNCIONARIO(ID),
  UNIQUE KEY UK_PED_NUM_ORC (EMPRESA_ID, NUMERO_ORCAMENTO),
  UNIQUE KEY UK_PED_NUM_PED (EMPRESA_ID, NUMERO_PEDIDO),
  KEY IX_PED_STATUS (EMPRESA_ID, TIPO, STATUS),
  KEY IX_PED_CLIENTE (CLIENTE_ID),
  KEY IX_PED_VEICULO (VEICULO_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Itens de mão de obra do pedido (um ou mais serviços)
CREATE TABLE IF NOT EXISTS PEDIDO_SERVICO (
  ID                  INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  PEDIDO_ID           INT UNSIGNED NOT NULL,
  SERVICO_ID          INT UNSIGNED NULL,            -- NULL = serviço avulso digitado
  DESCRICAO           VARCHAR(200) NOT NULL,
  FUNCIONARIO_ID      INT UNSIGNED NULL,            -- quem executa
  TEMPO_PREVISTO_MIN  INT UNSIGNED NOT NULL DEFAULT 60,
  HORAS               DECIMAL(6,2) NOT NULL DEFAULT 1.00,
  VALOR_HORA_CENT     BIGINT NOT NULL DEFAULT 0,
  VALOR_CENT          BIGINT NOT NULL DEFAULT 0,    -- horas x valor_hora ou valor fixo
  AUTORIZADO          TINYINT(1) NOT NULL DEFAULT 1, -- cliente pode recusar item
  EXECUTADO           TINYINT(1) NOT NULL DEFAULT 0,
  DESCRICAO_EXECUTADO TEXT NULL,                    -- relato do mecânico
  INICIADO_EM         DATETIME NULL,
  CONCLUIDO_EM        DATETIME NULL,
  CONSTRAINT FK_PS_PEDIDO FOREIGN KEY (PEDIDO_ID) REFERENCES PEDIDO(ID) ON DELETE CASCADE,
  CONSTRAINT FK_PS_SERVICO FOREIGN KEY (SERVICO_ID) REFERENCES SERVICO(ID),
  CONSTRAINT FK_PS_FUNC FOREIGN KEY (FUNCIONARIO_ID) REFERENCES FUNCIONARIO(ID),
  KEY IX_PS_PEDIDO (PEDIDO_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Peças do pedido
CREATE TABLE IF NOT EXISTS PEDIDO_PECA (
  ID              INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  PEDIDO_ID       INT UNSIGNED NOT NULL,
  PECA_ID         INT UNSIGNED NULL,                -- NULL = peça avulsa digitada
  DESCRICAO       VARCHAR(200) NOT NULL,
  QUANTIDADE      DECIMAL(10,3) NOT NULL DEFAULT 1,
  VALOR_UNIT_CENT BIGINT NOT NULL DEFAULT 0,
  VALOR_CENT      BIGINT NOT NULL DEFAULT 0,
  AUTORIZADO      TINYINT(1) NOT NULL DEFAULT 1,
  APLICADA        TINYINT(1) NOT NULL DEFAULT 0,    -- baixada no estoque / instalada
  CONSTRAINT FK_PP_PEDIDO FOREIGN KEY (PEDIDO_ID) REFERENCES PEDIDO(ID) ON DELETE CASCADE,
  CONSTRAINT FK_PP_PECA FOREIGN KEY (PECA_ID) REFERENCES PECA(ID),
  KEY IX_PP_PEDIDO (PEDIDO_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Sequências por empresa (numeração de orçamento e pedido)
CREATE TABLE IF NOT EXISTS SEQUENCIA (
  EMPRESA_ID INT UNSIGNED NOT NULL,
  NOME       VARCHAR(20)  NOT NULL,
  VALOR      INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (EMPRESA_ID, NOME),
  CONSTRAINT FK_SEQ_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
