-- v001_base — aOfficina: núcleo (empresa, oficinas, usuários, clientes, veículos,
-- catálogo de veículos, recursos e agenda, log de segurança).
-- Idempotente: CREATE TABLE IF NOT EXISTS. Dinheiro em centavos (BIGINT).
-- Charset utf8mb4 / InnoDB. Uma instância = uma empresa compradora (com N oficinas).

CREATE TABLE IF NOT EXISTS SCHEMA_MIGRATIONS (
  VERSAO      VARCHAR(10)  NOT NULL PRIMARY KEY,
  NOME        VARCHAR(120) NOT NULL,
  APLICADO_EM DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS EMPRESA (
  ID            INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  RAZAO_SOCIAL  VARCHAR(120) NOT NULL,
  FANTASIA      VARCHAR(80)  NOT NULL,
  CNPJ          CHAR(14)     NULL,
  IE            VARCHAR(20)  NULL,
  IM            VARCHAR(20)  NULL,
  TELEFONE      VARCHAR(20)  NULL,
  EMAIL         VARCHAR(120) NULL,
  CEP           CHAR(8)      NULL,
  LOGRADOURO    VARCHAR(120) NULL,
  NUMERO        VARCHAR(10)  NULL,
  COMPLEMENTO   VARCHAR(60)  NULL,
  BAIRRO        VARCHAR(60)  NULL,
  CIDADE        VARCHAR(60)  NULL,
  UF            CHAR(2)      NULL,
  LOGO_PATH     VARCHAR(255) NULL,
  CRIADO_EM     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS OFICINA (
  ID           INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  EMPRESA_ID   INT UNSIGNED NOT NULL,
  NOME         VARCHAR(80)  NOT NULL,
  CNPJ         CHAR(14)     NULL,
  TELEFONE     VARCHAR(20)  NULL,
  WHATSAPP     VARCHAR(20)  NULL,
  CEP          CHAR(8)      NULL,
  LOGRADOURO   VARCHAR(120) NULL,
  NUMERO       VARCHAR(10)  NULL,
  BAIRRO       VARCHAR(60)  NULL,
  CIDADE       VARCHAR(60)  NULL,
  UF           CHAR(2)      NULL,
  HORA_ABRE    TIME         NOT NULL DEFAULT '08:00:00',
  HORA_FECHA   TIME         NOT NULL DEFAULT '18:00:00',
  DIAS_SEMANA  VARCHAR(13)  NOT NULL DEFAULT '1,2,3,4,5,6',  -- 0=dom ... 6=sab
  ATIVO        TINYINT(1)   NOT NULL DEFAULT 1,
  CRIADO_EM    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_OFICINA_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Funcionários (mecânicos, atendentes...). Nem todo funcionário tem login.
CREATE TABLE IF NOT EXISTS FUNCIONARIO (
  ID           INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  EMPRESA_ID   INT UNSIGNED NOT NULL,
  OFICINA_ID   INT UNSIGNED NULL,
  NOME         VARCHAR(100) NOT NULL,
  CPF          CHAR(11)     NULL,
  FUNCAO       ENUM('MECANICO','ATENDENTE','GERENTE','FINANCEIRO','OUTRO') NOT NULL DEFAULT 'MECANICO',
  TELEFONE     VARCHAR(20)  NULL,
  COR_AGENDA   CHAR(7)      NOT NULL DEFAULT '#0F4C5C',
  ATIVO        TINYINT(1)   NOT NULL DEFAULT 1,
  CRIADO_EM    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_FUNC_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID),
  CONSTRAINT FK_FUNC_OFICINA FOREIGN KEY (OFICINA_ID) REFERENCES OFICINA(ID),
  UNIQUE KEY UK_FUNC_CPF (EMPRESA_ID, CPF)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS USUARIO (
  ID              INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  EMPRESA_ID      INT UNSIGNED NOT NULL,
  OFICINA_ID      INT UNSIGNED NULL,          -- NULL = acesso a todas as oficinas
  FUNCIONARIO_ID  INT UNSIGNED NULL,
  NOME            VARCHAR(100) NOT NULL,
  LOGIN           VARCHAR(60)  NOT NULL,
  EMAIL           VARCHAR(120) NULL,
  SENHA_HASH      VARCHAR(100) NOT NULL,      -- bcrypt, nunca texto puro
  NIVEL           TINYINT      NOT NULL DEFAULT 2,
  PRIMEIRO_ACESSO TINYINT(1)   NOT NULL DEFAULT 1,
  ATIVO           TINYINT(1)   NOT NULL DEFAULT 1,
  ULTIMO_LOGIN    DATETIME     NULL,
  CRIADO_EM       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_USU_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID),
  CONSTRAINT FK_USU_OFICINA FOREIGN KEY (OFICINA_ID) REFERENCES OFICINA(ID),
  CONSTRAINT FK_USU_FUNC FOREIGN KEY (FUNCIONARIO_ID) REFERENCES FUNCIONARIO(ID),
  UNIQUE KEY UK_USUARIO_LOGIN (LOGIN)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Equipamentos agendáveis: boxes/elevadores, scanner, alinhadora...
CREATE TABLE IF NOT EXISTS EQUIPAMENTO (
  ID           INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  OFICINA_ID   INT UNSIGNED NOT NULL,
  NOME         VARCHAR(60)  NOT NULL,
  TIPO         ENUM('BOX','ELEVADOR','SCANNER','ALINHADORA','OUTRO') NOT NULL DEFAULT 'BOX',
  COR_AGENDA   CHAR(7)      NOT NULL DEFAULT '#B87333',
  ATIVO        TINYINT(1)   NOT NULL DEFAULT 1,
  CONSTRAINT FK_EQUIP_OFICINA FOREIGN KEY (OFICINA_ID) REFERENCES OFICINA(ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS CLIENTE (
  ID            INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  EMPRESA_ID    INT UNSIGNED NOT NULL,
  TIPO_PESSOA   CHAR(1)      NOT NULL DEFAULT 'F',   -- F=física J=jurídica
  NOME          VARCHAR(120) NOT NULL,
  CPF_CNPJ      VARCHAR(14)  NULL,
  TELEFONE      VARCHAR(20)  NULL,
  WHATSAPP      VARCHAR(20)  NULL,
  EMAIL         VARCHAR(120) NULL,
  CEP           CHAR(8)      NULL,
  LOGRADOURO    VARCHAR(120) NULL,
  NUMERO        VARCHAR(10)  NULL,
  COMPLEMENTO   VARCHAR(60)  NULL,
  BAIRRO        VARCHAR(60)  NULL,
  CIDADE        VARCHAR(60)  NULL,
  UF            CHAR(2)      NULL,
  OBSERVACAO    TEXT         NULL,
  ATIVO         TINYINT(1)   NOT NULL DEFAULT 1,
  CRIADO_EM     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_CLI_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID),
  UNIQUE KEY UK_CLIENTE_DOC (EMPRESA_ID, CPF_CNPJ),
  KEY IX_CLIENTE_NOME (EMPRESA_ID, NOME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Catálogo de veículos (origem FIPE via importador; TIPO 1=carro 2=moto 3=caminhão)
CREATE TABLE IF NOT EXISTS CAT_MARCA (
  ID          INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  TIPO        TINYINT      NOT NULL DEFAULT 1,
  CODIGO_FIPE VARCHAR(10)  NOT NULL,
  NOME        VARCHAR(60)  NOT NULL,
  UNIQUE KEY UK_MARCA (TIPO, CODIGO_FIPE),
  KEY IX_MARCA_NOME (NOME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS CAT_MODELO (
  ID          INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  MARCA_ID    INT UNSIGNED NOT NULL,
  CODIGO_FIPE VARCHAR(10)  NOT NULL,
  NOME        VARCHAR(120) NOT NULL,
  ANOS_OK     TINYINT(1)   NOT NULL DEFAULT 0,   -- 1 = anos já importados
  CONSTRAINT FK_MODELO_MARCA FOREIGN KEY (MARCA_ID) REFERENCES CAT_MARCA(ID),
  UNIQUE KEY UK_MODELO (MARCA_ID, CODIGO_FIPE),
  KEY IX_MODELO_NOME (NOME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS CAT_ANO (
  ID          INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  MODELO_ID   INT UNSIGNED NOT NULL,
  CODIGO_FIPE VARCHAR(10)  NOT NULL,   -- ex.: 2014-3  (32000 = zero km)
  ANO         SMALLINT     NOT NULL,
  COMBUSTIVEL VARCHAR(20)  NULL,
  CONSTRAINT FK_ANO_MODELO FOREIGN KEY (MODELO_ID) REFERENCES CAT_MODELO(ID),
  UNIQUE KEY UK_ANO (MODELO_ID, CODIGO_FIPE),
  KEY IX_ANO (ANO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS VEICULO (
  ID            INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  EMPRESA_ID    INT UNSIGNED NOT NULL,
  CLIENTE_ID    INT UNSIGNED NOT NULL,
  PLACA         VARCHAR(8)   NOT NULL,          -- sem hífen, maiúscula (ABC1D23)
  TIPO          TINYINT      NOT NULL DEFAULT 1,
  MARCA         VARCHAR(60)  NOT NULL,
  MODELO        VARCHAR(120) NOT NULL,
  ANO_FAB       SMALLINT     NULL,
  ANO_MODELO    SMALLINT     NULL,
  COR           VARCHAR(30)  NULL,
  COMBUSTIVEL   VARCHAR(20)  NULL,
  CHASSI        VARCHAR(17)  NULL,
  RENAVAM       VARCHAR(11)  NULL,
  KM_ATUAL      INT UNSIGNED NULL,
  CAT_MODELO_ID INT UNSIGNED NULL,
  CODIGO_FIPE   VARCHAR(10)  NULL,
  OBSERVACAO    TEXT         NULL,
  ATIVO         TINYINT(1)   NOT NULL DEFAULT 1,
  CRIADO_EM     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_VEI_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA(ID),
  CONSTRAINT FK_VEI_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE(ID),
  CONSTRAINT FK_VEI_CATMOD FOREIGN KEY (CAT_MODELO_ID) REFERENCES CAT_MODELO(ID),
  UNIQUE KEY UK_VEICULO_PLACA (EMPRESA_ID, PLACA)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Agenda: um compromisso por oficina, opcionalmente ligado a funcionário e/ou equipamento.
CREATE TABLE IF NOT EXISTS AGENDA (
  ID              INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  OFICINA_ID      INT UNSIGNED NOT NULL,
  INICIO          DATETIME     NOT NULL,
  FIM             DATETIME     NOT NULL,
  TIPO            ENUM('SERVICO','REVISAO','ORCAMENTO','RETORNO','BLOQUEIO') NOT NULL DEFAULT 'SERVICO',
  STATUS          ENUM('AGENDADO','CONFIRMADO','CHEGOU','EM_ATENDIMENTO','CONCLUIDO','FALTOU','CANCELADO') NOT NULL DEFAULT 'AGENDADO',
  CLIENTE_ID      INT UNSIGNED NULL,
  VEICULO_ID      INT UNSIGNED NULL,
  FUNCIONARIO_ID  INT UNSIGNED NULL,
  EQUIPAMENTO_ID  INT UNSIGNED NULL,
  TITULO          VARCHAR(120) NOT NULL,
  DESCRICAO       TEXT         NULL,
  GUINCHO         TINYINT(1)   NOT NULL DEFAULT 0,
  CRIADO_POR      INT UNSIGNED NULL,
  CRIADO_EM       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_AG_OFICINA FOREIGN KEY (OFICINA_ID) REFERENCES OFICINA(ID),
  CONSTRAINT FK_AG_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE(ID),
  CONSTRAINT FK_AG_VEICULO FOREIGN KEY (VEICULO_ID) REFERENCES VEICULO(ID),
  CONSTRAINT FK_AG_FUNC FOREIGN KEY (FUNCIONARIO_ID) REFERENCES FUNCIONARIO(ID),
  CONSTRAINT FK_AG_EQUIP FOREIGN KEY (EQUIPAMENTO_ID) REFERENCES EQUIPAMENTO(ID),
  CONSTRAINT FK_AG_USUARIO FOREIGN KEY (CRIADO_POR) REFERENCES USUARIO(ID),
  KEY IX_AGENDA_OFI_INICIO (OFICINA_ID, INICIO),
  KEY IX_AGENDA_FUNC (FUNCIONARIO_ID, INICIO),
  KEY IX_AGENDA_EQUIP (EQUIPAMENTO_ID, INICIO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS SECURITY_LOG (
  ID       BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  QUANDO   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  EVENTO   VARCHAR(40)  NOT NULL,
  LOGIN    VARCHAR(60)  NULL,
  IP       VARCHAR(45)  NULL,
  DETALHE  VARCHAR(255) NULL,
  KEY IX_SEC_QUANDO (QUANDO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
